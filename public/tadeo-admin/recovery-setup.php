    } else {
        $currentPassword = (string)($_POST['current_password'] ?? '');
        $appPassword = str_replace(' ', '', trim((string)($_POST['app_password'] ?? '')));
        $protectionCode = trim((string)($_POST['protection_code'] ?? ''));
        $protectionCodeConfirm = trim((string)($_POST['protection_code_confirm'] ?? ''));

        if (!recovery_setup_admin_password_valid($pdo, (int)$admin['id'], $currentPassword)) {
            $errors[] = 'Password-i aktual nuk është i saktë.';
        }

        foreach (['sender_email', 'protected_email', 'recovery_email'] as $field) {
            if (!filter_var($form[$field], FILTER_VALIDATE_EMAIL)) {
                $errors[] = 'Të gjitha adresat e email-it duhet të jenë të vlefshme.';
                break;
            }
        }

        if ($form['protected_email'] !== '' && strcasecmp($form['protected_email'], $form['recovery_email']) === 0) {
            $errors[] = 'Email-i i mbrojtur dhe email-i i hyrjes/rikuperimit duhet të jenë të ndryshëm.';
        }

        if (strlen($appPassword) !== 16) {
            $errors[] = 'Google App Password duhet të ketë 16 karaktere.';
        }

        if (strlen($protectionCode) < 6) {
            $errors[] = 'Kodi privat i mbrojtjes duhet të ketë të paktën 6 karaktere.';
        } elseif ($protectionCode !== $protectionCodeConfirm) {
            $errors[] = 'Konfirmimi i kodit privat nuk përputhet.';
        }

        if (!$errors) {
            try {
                recovery_setup_ensure_schema($pdo);
                $checks[] = 'Databaza dhe tabela password_reset_codes: në rregull';

                if (!is_writable(dirname($recoveryConfigPath))) {
                    throw new RuntimeException('Dosja includes nuk lejon shkrim nga PHP.');
                }
                $checks[] = 'Ruajtja private e konfigurimit: në rregull';

                $smtpConfig = [
                    'host' => 'smtp.gmail.com',
                    'port' => 587,
                    'username' => $form['sender_email'],
                    'password' => $appPassword,
                    'from_email' => $form['sender_email'],
                    'from_name' => 'Bar Tadeo',
                ];

                $testSubject = 'Bar Tadeo - Test i rikuperimit';
                $testBody = "Ky është një email test nga konfigurimi i rikuperimit të Bar Tadeo.\n\n"
                    . "Nëse e more këtë email, lidhja Gmail SMTP, TLS dhe autentikimi funksionojnë.";

                smtp_send_text_email_with_config(
                    $smtpConfig,
                    $form['protected_email'],
                    $testSubject,
                    $testBody
                );
                $checks[] = 'Gmail SMTP/TLS, autentikimi dhe email-i i mbrojtur: në rregull';

                smtp_send_text_email_with_config(
                    $smtpConfig,
                    $form['recovery_email'],
                    $testSubject,
                    $testBody
                );
                $checks[] = 'Email-i i hyrjes/rikuperimit: në rregull';

                $protectionCodeHash = password_hash($protectionCode, PASSWORD_DEFAULT);
                if ($protectionCodeHash === false) {
                    throw new RuntimeException('Hash-i i kodit privat nuk u krijua dot.');
                }
                $checks[] = 'Kodi privat u ruajt si hash: në rregull';

                $configContents = recovery_setup_config_contents(
                    $form['sender_email'],
                    $appPassword,
                    $form['protected_email'],
                    $protectionCodeHash
                );

                $pdo->beginTransaction();
                try {
                    $stmt = $pdo->prepare(
                        'INSERT INTO settings (setting_key, setting_value) VALUES (?, ?) '
                        . 'ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value)'
                    );
                    $stmt->execute(['recovery_email', $form['recovery_email']]);
                    $stmt->execute(['protected_recovery_enabled', '1']);

                    recovery_setup_write_private_file($recoveryConfigPath, $configContents);
                    $pdo->commit();
                } catch (Throwable $e) {
                    if ($pdo->inTransaction()) {
                        $pdo->rollBack();
                    }
                    if (is_file($recoveryConfigPath)) {
                        @unlink($recoveryConfigPath);
                    }
                    throw $e;
                }

                $checks[] = 'Cilësimet e rikuperimit u ruajtën: në rregull';
                $checks[] = 'Skedari privat recovery.local.php u krijua: në rregull';
                $completed = true;
            } catch (Throwable $e) {
                $errors[] = $e->getMessage();
            }
        }
    }
}
