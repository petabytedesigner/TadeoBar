function recovery_setup_ensure_schema(PDO $pdo): void
{
    $pdo->exec(<<<'SQL'
CREATE TABLE IF NOT EXISTS `password_reset_codes` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `admin_id` int unsigned NOT NULL,
  `code_hash` varchar(255) NOT NULL,
  `request_ip_hash` char(64) NOT NULL,
  `attempts` tinyint unsigned NOT NULL DEFAULT 0,
  `expires_at` datetime NOT NULL,
  `used_at` datetime DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_password_reset_ip_time` (`request_ip_hash`,`created_at`),
  KEY `idx_password_reset_admin_active` (`admin_id`,`used_at`,`expires_at`),
  CONSTRAINT `fk_password_reset_admin` FOREIGN KEY (`admin_id`) REFERENCES `admins` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
SQL);

    $stmt = $pdo->prepare(
        'INSERT IGNORE INTO settings (setting_key, setting_value) VALUES (?, ?)'
    );
    $stmt->execute(['protected_recovery_enabled', '1']);
}

function recovery_setup_admin_password_valid(PDO $pdo, int $adminId, string $password): bool
{
    $stmt = $pdo->prepare(
        'SELECT password_hash FROM admins WHERE id = ? AND is_active = 1 LIMIT 1'
    );
    $stmt->execute([$adminId]);
    $hash = $stmt->fetchColumn();

    return $hash !== false && password_verify($password, (string)$hash);
}

function recovery_setup_config_contents(
    string $senderEmail,
    string $appPassword,
    string $protectedEmail,
    string $protectionCodeHash
): string {
    return "<?php\n"
        . "declare(strict_types=1);\n\n"
        . "/**\n"
        . " * Private Bar Tadeo password-recovery configuration.\n"
        . " * Generated by /tadeo-admin/recovery-setup.php.\n"
        . " * NEVER commit this file to GitHub.\n"
        . " */\n\n"
        . "const RECOVERY_SETUP_COMPLETE = true;\n"
        . "const SMTP_HOST = 'smtp.gmail.com';\n"
        . "const SMTP_PORT = 587;\n"
        . 'const SMTP_USERNAME = ' . var_export($senderEmail, true) . ";\n"
        . 'const SMTP_PASSWORD = ' . var_export($appPassword, true) . ";\n"
        . 'const SMTP_FROM_EMAIL = ' . var_export($senderEmail, true) . ";\n"
        . "const SMTP_FROM_NAME = 'Bar Tadeo';\n"
        . 'const PROTECTED_RECOVERY_EMAIL = ' . var_export($protectedEmail, true) . ";\n"
        . 'const PROTECTED_RECOVERY_CODE_HASH = ' . var_export($protectionCodeHash, true) . ";\n";
}

function recovery_setup_write_private_file(string $targetPath, string $contents): void
{
    if (file_exists($targetPath)) {
        throw new RuntimeException('Konfigurimi i rikuperimit ekziston tashmë dhe nuk do të mbishkruhet.');
    }

    $dir = dirname($targetPath);
    if (!is_dir($dir) || !is_writable($dir)) {
        throw new RuntimeException('Serveri nuk lejon krijimin e skedarit privat recovery.local.php.');
    }

    $tmpPath = $targetPath . '.tmp-' . bin2hex(random_bytes(6));
    $written = @file_put_contents($tmpPath, $contents, LOCK_EX);

    if ($written === false || $written !== strlen($contents)) {
        @unlink($tmpPath);
        throw new RuntimeException('Konfigurimi i rikuperimit nuk u shkrua dot në server.');
    }

    @chmod($tmpPath, 0600);

    if (file_exists($targetPath) || !@rename($tmpPath, $targetPath)) {
        @unlink($tmpPath);
        throw new RuntimeException('Konfigurimi i rikuperimit nuk u aktivizua dot në server.');
    }

    @chmod($targetPath, 0600);
}

